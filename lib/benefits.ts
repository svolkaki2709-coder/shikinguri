export type BenefitCategory = "子育て・教育" | "医療" | "働く・休む" | "年金" | "住宅" | "税金"

/** 世帯の状況。ライフプランに登録された情報から組み立てる */
export interface HouseholdContext {
  thisYear: number
  /** 家族全員（名前・年齢・続柄） */
  people: { name: string; age: number; relation: string }[]
  /** 子の年齢一覧 */
  childAges: number[]
  hasSpouse: boolean
  /** 本人の年収（円）。給与明細や収入登録から推定。不明なら null */
  annualIncome: number | null
  /** 住宅ローンを登録しているか */
  hasMortgage: boolean
  /** 今後のライフイベントのカテゴリ（教育・出産など） */
  plannedCategories: string[]
}

/** どのくらい自分ごとか */
export type RelevanceLevel = "now" | "soon" | "someday"

export interface Relevance {
  level: RelevanceLevel
  /** なぜ関係しそうなのか（この世帯の事情に即した一言） */
  reason: string
}

export interface Benefit {
  id: string
  category: BenefitCategory
  title: string
  /** 一言でいうと何の制度か */
  summary: string
  /** いくらもらえる／いくら減るか */
  amount: string
  /** 主な条件 */
  conditions: string[]
  /** どこに・いつ申請するか */
  howTo: string
  /** 見落としやすい点、損をしやすい点 */
  tips?: string
  /** 確認先 */
  source: string
  /** この世帯に関係しそうか。関係しなければ null */
  relevance: (ctx: HouseholdContext) => Relevance | null
}

